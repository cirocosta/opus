//go:build amd64 && !purego

#include "textflag.h"

// four independent butterflies use AoS real/imaginary lanes. m is a positive
// multiple of four; fout contains 5*m complex values and tw has m/4 blocks.
// mul/add remain separate and ordered; opposite subtractions preserve signed zero.
TEXT ·fft5AVX2(SB), NOSPLIT, $0-40
	MOVQ fout+0(FP), AX
	MOVQ tw+8(FP), BX
	MOVQ m+16(FP), DX
	MOVQ DX, CX
	SHRQ $2, CX
	SHLQ $3, DX
	LEAQ (AX)(DX*1), R8
	LEAQ (R8)(DX*1), R9
	LEAQ (R9)(DX*1), R10
	LEAQ (R10)(DX*1), R11
fft5_block:
	VMOVUPS (AX), Y0
	VMOVUPS (R8), Y1
	VMOVUPS 0(BX), Y10
	VSHUFPS $0xA0, Y10, Y10, Y11
	VSHUFPS $0xF5, Y10, Y10, Y12
	VSHUFPS $0xB1, Y1, Y1, Y13
	VMULPS Y11, Y1, Y1
	VMULPS Y12, Y13, Y13
	VADDSUBPS Y13, Y1, Y1
	VMOVUPS (R9), Y2
	VMOVUPS 32(BX), Y10
	VSHUFPS $0xA0, Y10, Y10, Y11
	VSHUFPS $0xF5, Y10, Y10, Y12
	VSHUFPS $0xB1, Y2, Y2, Y13
	VMULPS Y11, Y2, Y2
	VMULPS Y12, Y13, Y13
	VADDSUBPS Y13, Y2, Y2
	VMOVUPS (R10), Y3
	VMOVUPS 64(BX), Y10
	VSHUFPS $0xA0, Y10, Y10, Y11
	VSHUFPS $0xF5, Y10, Y10, Y12
	VSHUFPS $0xB1, Y3, Y3, Y13
	VMULPS Y11, Y3, Y3
	VMULPS Y12, Y13, Y13
	VADDSUBPS Y13, Y3, Y3
	VMOVUPS (R11), Y4
	VMOVUPS 96(BX), Y10
	VSHUFPS $0xA0, Y10, Y10, Y11
	VSHUFPS $0xF5, Y10, Y10, Y12
	VSHUFPS $0xB1, Y4, Y4, Y13
	VMULPS Y11, Y4, Y4
	VMULPS Y12, Y13, Y13
	VADDSUBPS Y13, Y4, Y4
	VADDPS Y4, Y1, Y5
	VSUBPS Y4, Y1, Y6
	VADDPS Y3, Y2, Y7
	VSUBPS Y3, Y2, Y8
	VADDPS Y7, Y5, Y9
	VADDPS Y9, Y0, Y9
	VMOVUPS Y9, (AX)
// s5 = s0 + (s7*ya.R + s8*yb.R).
	VBROADCASTSS yaR+24(FP), Y13
	VBROADCASTSS ybR+32(FP), Y14
	VMULPS Y13, Y5, Y9
	VMULPS Y14, Y7, Y10
	VADDPS Y10, Y9, Y9
	VADDPS Y9, Y0, Y9
// s6 = swapped(s10*ya.I + s9*yb.I), with negated imaginary lanes.
	VBROADCASTSS yaI+28(FP), Y13
	VBROADCASTSS ybI+36(FP), Y14
	VMULPS Y13, Y6, Y10
	VMULPS Y14, Y8, Y11
	VADDPS Y11, Y10, Y10
	VSHUFPS $0xB1, Y10, Y10, Y10
	VXORPS ·fft5OddSign(SB), Y10, Y10
	VSUBPS Y10, Y9, Y11
	VADDPS Y10, Y9, Y12
	VMOVUPS Y11, (R8)
	VMOVUPS Y12, (R11)
// s11 = s0 + (s7*yb.R + s8*ya.R).
	VBROADCASTSS ybR+32(FP), Y13
	VBROADCASTSS yaR+24(FP), Y14
	VMULPS Y13, Y5, Y9
	VMULPS Y14, Y7, Y10
	VADDPS Y10, Y9, Y9
	VADDPS Y9, Y0, Y9
// s12.R = s9.I*ya.I - s10.I*yb.I; s12.I reverses the subtraction.
	VBROADCASTSS yaI+28(FP), Y13
	VBROADCASTSS ybI+36(FP), Y14
	VMULPS Y13, Y8, Y10
	VMULPS Y14, Y6, Y11
	VSHUFPS $0xB1, Y10, Y10, Y10
	VSHUFPS $0xB1, Y11, Y11, Y11
	VSUBPS Y11, Y10, Y12
	VSUBPS Y10, Y11, Y13
	VBLENDPS $0xAA, Y13, Y12, Y12
	VADDPS Y12, Y9, Y10
	VSUBPS Y12, Y9, Y11
	VMOVUPS Y10, (R9)
	VMOVUPS Y11, (R10)
	ADDQ $32, AX
	ADDQ $32, R8
	ADDQ $32, R9
	ADDQ $32, R10
	ADDQ $32, R11
	ADDQ $128, BX
	DECQ CX
	JNZ fft5_block
	VZEROUPPER
	RET

DATA ·fft5OddSign+0(SB)/8, $0x8000000000000000
DATA ·fft5OddSign+8(SB)/8, $0x8000000000000000
DATA ·fft5OddSign+16(SB)/8, $0x8000000000000000
DATA ·fft5OddSign+24(SB)/8, $0x8000000000000000
GLOBL ·fft5OddSign(SB), RODATA, $32
