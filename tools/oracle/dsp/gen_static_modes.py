"""Generate opus/internal/dsp/static_modes.go from libopus celt/static_modes_float.h.

Usage: python3 -I gen_static_modes.py <static_modes_float.h> <out.go>
Only the non-QEXT 48 kHz / 960 section (before mode48000_960_120) is used.
"""

import re
import sys

src = open(sys.argv[1]).read()
end = src.index("static const CELTMode mode48000_960_120")
mode_end = src.index("};", end)
mode_src = src[end:mode_end]
src = src[:end]

arr_re = re.compile(
    r"static const ((?:unsigned )?\w+) (\w+)\[(\d+)\] = \{(.*?)\};", re.S
)
tables = {}
for m in arr_re.finditer(src):
    ctype, name, n, body = m.group(1), m.group(2), int(m.group(3)), m.group(4)
    tables[name] = (ctype, n, body)

state_re = re.compile(
    r"static const kiss_fft_state (\w+) = \{\s*(\d+),\s*/\* nfft \*/\s*([-0-9.e]+)f,\s*/\* scale \*/\s*(-?\d+),\s*/\* shift \*/\s*\{([^}]*)\},\s*/\* factors \*/\s*(\w+),\s*/\* bitrev \*/\s*(\w+),",
    re.S,
)
states = list(state_re.finditer(src))
assert len(states) == 4, len(states)


def fl(tok):
    tok = tok.strip()
    assert tok.endswith("f"), tok
    v = tok[:-1]
    if float(v) == 0.0 and v.startswith("-"):
        return "negZero"
    return v


def goname(c):
    special = {
        "window120": "Window120",
        "logN400": "LogN400",
        "cache_index50": "CacheIndex50",
        "cache_bits50": "CacheBits50",
        "cache_caps50": "CacheCaps50",
        "fft_twiddles48000_960": "FFTTwiddles48000_960",
        "fft_bitrev480": "FFTBitrev480",
        "fft_bitrev240": "FFTBitrev240",
        "fft_bitrev120": "FFTBitrev120",
        "fft_bitrev60": "FFTBitrev60",
        "mdct_twiddles960": "MDCTTwiddles960",
        "fft_state48000_960_0": "FFTState48000_960_0",
        "fft_state48000_960_1": "FFTState48000_960_1",
        "fft_state48000_960_2": "FFTState48000_960_2",
        "fft_state48000_960_3": "FFTState48000_960_3",
    }
    return special[c]


gotype = {
    "celt_coef": "float32",
    "opus_int16": "int16",
    "unsigned char": "uint8",
}

out = []
w = out.append
w("// Code generated by gen_static_modes.py from libopus 1.6.1; DO NOT EDIT.")
w("")
w("// Ported from libopus 1.6.1 celt/static_modes_float.h.")
w("")
w("package dsp")
w("")
w('import "math"')
w("")
w("// negZero is the float -0.0f that appears in the C tables.")
w("var negZero = float32(math.Copysign(0, -1))")
w("")


def emit_scalar(cname, ctype, n, body, per_line):
    toks = [t for t in body.replace("\n", " ").split(",") if t.strip()]
    assert len(toks) == n, (cname, len(toks), n)
    gt = gotype[ctype]
    w(f"// {goname(cname)} is {cname}[{n}] from static_modes_float.h.")
    w(f"var {goname(cname)} = []{gt}{{")
    vals = [fl(t) if gt == "float32" else t.strip() for t in toks]
    for i in range(0, n, per_line):
        w("\t" + ", ".join(vals[i : i + per_line]) + ",")
    w("}")
    w("")


def emit_cpx(cname, n, body):
    pairs = re.findall(r"\{([^,]+),([^}]+)\}", body)
    assert len(pairs) == n, (cname, len(pairs))
    w(f"// {goname(cname)} is {cname}[{n}] from static_modes_float.h.")
    w(f"var {goname(cname)} = []KissTwiddleCpx{{")
    for a, b in pairs:
        w(f"\t{{{fl(a)}, {fl(b)}}},")
    w("}")
    w("")


order = [
    "window120",
    "logN400",
    "cache_index50",
    "cache_bits50",
    "cache_caps50",
    "fft_twiddles48000_960",
    "fft_bitrev480",
    "fft_bitrev240",
    "fft_bitrev120",
    "fft_bitrev60",
    "mdct_twiddles960",
]
for name in order:
    ctype, n, body = tables[name]
    if ctype == "kiss_twiddle_cpx":
        emit_cpx(name, n, body)
    elif ctype == "celt_coef":
        emit_scalar(name, ctype, n, body, 5)
    else:
        emit_scalar(name, ctype, n, body, 15)
assert set(t for t in tables if not t.startswith("qext_")) == set(order)

for m in states:
    name, nfft, scale, shift, factors, bitrev, tw = m.groups()
    facs = [f.strip() for f in factors.split(",") if f.strip()]
    assert len(facs) == 16
    w(f"// {goname(name)} is {name} from static_modes_float.h.")
    w(f"var {goname(name)} = KissFFTState{{")
    w(f"\tNfft:     {nfft},")
    w(f"\tScale:    {scale},")
    w(f"\tShift:    {shift},")
    w(f"\tFactors:  [2 * MaxFactors]int16{{{', '.join(facs)}}},")
    w(f"\tBitrev:   {goname(bitrev)},")
    w(f"\tTwiddles: {goname(tw)},")
    w("}")
    w("")

# Mode scalars and the mdct lookup.
mfields = re.findall(r"^(.*?),\s*/\* (\w+) \*/", mode_src, re.M)
mf = {k: v.strip() for v, k in mfields}
pre = [fl(t) for t in re.findall(r"[-0-9.e]+f", mf["preemph"])]
mdct = re.match(r"\{(\d+), (\d+), \{([^}]*)\}, (\w+)\}", mf["mdct"])
mdct_n, mdct_max, mdct_states, mdct_trig = mdct.groups()
st_names = [s.strip().lstrip("&") for s in mdct_states.split(",") if s.strip()]
cache = re.match(r"\{(\d+), (\w+), (\w+), (\w+)\}", mf["cache"]).groups()

w("// MDCT48000x960 is the mdct field of mode48000_960_120 (static_modes_float.h).")
w("var MDCT48000x960 = MDCTLookup{")
w(f"\tN:        {mdct_n},")
w(f"\tMaxShift: {mdct_max},")
w("\tKFFT:     [4]*KissFFTState{" + ", ".join("&" + goname(s) for s in st_names) + "},")
w(f"\tTrig:     {goname(mdct_trig)},")
w("}")
w("")
w("// StaticMode holds the raw fields of a static CELTMode from")
w("// static_modes_float.h. The eBands and allocVectors tables are not in that")
w("// header (they are eband5ms and band_allocation in celt/modes.c), so the")
w("// celt package supplies them when it builds its mode.")
w("type StaticMode struct {")
w("\tFs             int32")
w("\tOverlap        int")
w("\tNbEBands       int")
w("\tEffEBands      int")
w("\tPreemph        [4]float32")
w("\tMaxLM          int")
w("\tNbShortMdcts   int")
w("\tShortMdctSize  int")
w("\tNbAllocVectors int")
w("\tLogN           []int16")
w("\tWindow         []float32")
w("\tMDCT           *MDCTLookup")
w("\tCacheSize      int")
w("\tCacheIndex     []int16")
w("\tCacheBits      []uint8")
w("\tCacheCaps      []uint8")
w("}")
w("")
w("// Mode48000_960_120 is mode48000_960_120 from static_modes_float.h,")
w("// without eBands and allocVectors.")
w("var Mode48000_960_120 = StaticMode{")
w(f"\tFs:             {mf['Fs']},")
w(f"\tOverlap:        {mf['overlap']},")
w(f"\tNbEBands:       {mf['nbEBands']},")
w(f"\tEffEBands:      {mf['effEBands']},")
w(f"\tPreemph:        [4]float32{{{', '.join(pre)}}},")
w(f"\tMaxLM:          {mf['maxLM']},")
w(f"\tNbShortMdcts:   {mf['nbShortMdcts']},")
w(f"\tShortMdctSize:  {mf['shortMdctSize']},")
w(f"\tNbAllocVectors: {mf['nbAllocVectors']},")
w(f"\tLogN:           {goname(mf['logN'])},")
w(f"\tWindow:         {goname(mf['window'])},")
w("\tMDCT:           &MDCT48000x960,")
w(f"\tCacheSize:      {cache[0]},")
w(f"\tCacheIndex:     {goname(cache[1])},")
w(f"\tCacheBits:      {goname(cache[2])},")
w(f"\tCacheCaps:      {goname(cache[3])},")
w("}")

open(sys.argv[2], "w").write("\n".join(out) + "\n")
