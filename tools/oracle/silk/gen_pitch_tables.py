"""Generate literal Go pitch tables from libopus 1.6.1 silk/pitch_est_tables.c.

Usage: uv run python gen_pitch_tables.py <pitch_est_tables.c> <out.go>
"""

import ast
import re
import subprocess
import sys
from pathlib import Path

source_path = Path(sys.argv[1])
source = source_path.read_text()
source = re.sub(r"/\*.*?\*/", "", source, flags=re.S)
defines = source_path.with_name("pitch_est_defines.h").read_text()
for macro in (
    "PE_NB_CBKS_STAGE3_MIN",
    "PE_NB_CBKS_STAGE3_MID",
    "PE_NB_CBKS_STAGE3_MAX",
):
    value = re.search(r"#define\s+" + macro + r"\s+(\d+)", defines).group(1)
    source = re.sub(r"\b" + macro + r"\b", value, source)

arrays = [
    ("silk_CB_lags_stage2_10_ms", "cbLagsStage2_10Ms", (2, 3)),
    ("silk_CB_lags_stage3_10_ms", "cbLagsStage3_10Ms", (2, 12)),
    ("silk_Lag_range_stage3_10_ms", "lagRangeStage3_10Ms", (2, 2)),
    ("silk_CB_lags_stage2", "cbLagsStage2", (4, 11)),
    ("silk_CB_lags_stage3", "cbLagsStage3", (4, 34)),
    ("silk_Lag_range_stage3", "lagRangeStage3", (3, 4, 2)),
    ("silk_nb_cbk_searchs_stage3", "nbCbkSearchsStage3", (3,)),
]


def literal(values, shape, depth=0):
    assert len(values) == shape[0], (len(values), shape)
    if len(shape) == 1:
        assert all(isinstance(v, int) and -128 <= v <= 127 for v in values)
        return "{" + ", ".join(map(str, values)) + "}"
    rows = [
        "\t" * (depth + 1) + literal(row, shape[1:], depth + 1) + "," for row in values
    ]
    return "{\n" + "\n".join(rows) + "\n" + "\t" * depth + "}"


output = [
    "// Code generated by gen_pitch_tables.py from libopus 1.6.1; DO NOT EDIT.",
    "// Ported from libopus 1.6.1 silk/pitch_est_tables.c.",
    "",
    "package silk",
    "",
]
for cname, goname, shape in arrays:
    body = re.search(
        r"\b" + cname + r"\s*(?:\[[^]]+\]\s*)+=\s*(\{.*?\});", source, re.S
    ).group(1)
    values = ast.literal_eval(body.replace("{", "[").replace("}", "]"))
    gotype = "".join(f"[{n}]" for n in shape) + "int8"
    output += [
        f"// {goname} is {cname}.",
        f"var {goname} = {gotype}" + literal(values, shape),
        "",
    ]
formatted = subprocess.run(
    ["gofmt"], input="\n".join(output), text=True, check=True, capture_output=True
).stdout
Path(sys.argv[2]).write_text(formatted)
