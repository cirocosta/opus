#!/usr/bin/env bash
# Regenerates the opus/internal/celt goldens.
#
# Decoder (drv.c, encf.c, hyb.c):
#   testdata/*.pk               packets of the reference CELT encoder (drv enc)
#   testdata/vectors_golden.txt CELT-only frames of the RFC vectors, with loss
#   testdata/synth_golden.txt   the *.pk files and random packets
#   testdata/encf_golden.txt    shared band/energy/allocation/PVQ helpers
#   testdata/hybrid_v12_*.log.gz  replay logs of every CELT call that
#                               opus_decode makes (ld --wrap); the full
#                               set for all vectors goes to $W/hyblogs, which
#                               TestHybridReplay reads from CELT_HYBRID_LOGS.
# Encoder (encdrv.c, gen_cases.py):
#   testdata/enc_pcm.raw.gz     2.4 s PCM excerpt of the decoded vectors
#   testdata/enc_golden.txt     core cases on the excerpt
#   testdata/enc_vectors_golden.txt  full decoded vectors
#
# The reference is the default configuration, so celt_decode_with_ec_dred
# takes no LPCNetPLCState and the decoder complexity has no effect.
. "$(dirname "$0")/../lib.sh"
oracle_init celt "OPUS_SRC OPUS_REF OPUS_TESTVECTORS" "$@"

V=$OPUS_TESTVECTORS
L=$OPUS_REF/.libs/libopus.a
F="$ORACLE_CFLAGS -DHAVE_CONFIG_H -I$OPUS_REF -I$OPUS_SRC/celt -I$OPUS_SRC/include -I$OPUS_SRC/silk"
$CC $F -o "$W/drv" "$HERE/drv.c" "$L" -lm
$CC $F -o "$W/encf" "$HERE/encf.c" "$L" -lm
$CC $F -o "$W/hyb" "$HERE/hyb.c" -Wl,--wrap=celt_decode_with_ec_dred \
	-Wl,--wrap=celt_decode_with_ec -Wl,--wrap=opus_custom_decoder_ctl "$L" -lm
$CC $F -o "$W/encdrv" "$HERE/encdrv.c" "$L" -lm

TD=internal/celt/testdata

# drv enc: out ch start bitrate fsz nframes complexity kind vbr
for spec in "hyb17_m960 1 17 32000 960 120 4 1 0" "hyb17_s480 2 17 48000 480 150 4 2 1" \
	"hyb17_s960 2 17 24000 960 120 4 2 0" "full_s240 2 0 96000 240 160 8 2 1" \
	"full_m120 1 0 24000 120 200 1 1 0"; do
	set -- $spec
	oracle_out $TD/$1.pk
	"$W/drv" enc "$O" "${@:2}"
done

field() { sed "s/.*$1=\([0-9a-f]*\).*/\1/"; }

oracle_out $TD/vectors_golden.txt
vec() { # v ch fs loss accum cx
	local out
	out=$("$W/drv" vec "$V/testvector$1.bit" "$2" "$3" "$4" "$5" "$6")
	echo "vec v=$1 ch=$2 fs=$3 loss=$4 accum=$5 cx=$6 hash=$(echo "$out" | field hash) frames=$(echo "$out" | field frames)"
}
{
	echo "# Generated by tools/oracle/celt/gen.sh (drv.c vec mode)."
	echo "# vec: CELT-only frames of testvectorNN.bit; ch=output channels, fs=rate,"
	echo "# loss=pattern (0 none, 1 random+bursts, 2 long bursts), accum, cx=decoder"
	echo "# complexity (no effect without deep PLC)."
	for v in 01 07 08 09 10 11; do
		for ch in 1 2; do vec $v $ch 48000 0 0 0; done
		vec $v 2 48000 1 0 0
		vec $v 1 48000 2 0 0
	done
	for v in 01 07 08 11; do
		for fs in 24000 16000 12000 8000; do vec $v 2 $fs 1 0 0; done
		vec $v 1 16000 0 1 0
		vec $v 2 48000 0 1 0
		vec $v 2 48000 1 0 10
		vec $v 2 48000 1 0 5
		vec $v 1 48000 2 0 5
		vec $v 2 16000 1 1 5
	done
} >"$O"

oracle_out $TD/synth_golden.txt
pk() { # file ch sc start fsz fs loss cx
	local out
	out=$("$W/drv" pk "$OUT/$TD/$1" "$2" "$3" "$4" "$5" "$6" "$7" "$8")
	echo "pk file=$1 ch=$2 sc=$3 start=$4 fsz=$5 fs=$6 loss=$7 cx=$8 hash=$(echo "$out" | field hash) frames=$(echo "$out" | field frames)"
}
rnd() { # seed n ch fs
	local out
	out=$("$W/drv" rnd "$1" "$2" "$3" "$4")
	echo "rnd seed=$1 n=$2 ch=$3 fs=$4 hash=$(echo "$out" | field hash) frames=$(echo "$out" | field frames)"
}
{
	echo "# Generated by tools/oracle/celt/gen.sh (drv.c pk and rnd modes)."
	echo "# pk: decode packets of the reference CELT encoder (testdata/*.pk)."
	echo "# rnd: decode random packets with random frame size, bands and channels."
	pk hyb17_m960.pk 1 1 17 960 48000 0 0
	pk hyb17_m960.pk 2 1 17 960 48000 1 0
	pk hyb17_m960.pk 1 1 17 960 16000 2 0
	pk hyb17_s480.pk 2 2 17 480 48000 0 0
	pk hyb17_s480.pk 2 2 17 480 48000 1 0
	pk hyb17_s480.pk 1 2 17 480 48000 1 0
	pk hyb17_s960.pk 2 2 17 960 48000 0 0
	pk hyb17_s960.pk 2 2 17 960 48000 1 5
	pk hyb17_s960.pk 1 2 17 960 24000 2 0
	pk full_s240.pk 2 2 0 240 48000 0 0
	pk full_s240.pk 2 2 0 240 48000 1 5
	pk full_s240.pk 1 2 0 240 48000 0 0
	pk full_s240.pk 2 2 0 240 12000 2 10
	pk full_m120.pk 1 1 0 120 48000 0 0
	pk full_m120.pk 1 1 0 120 48000 1 5
	pk full_m120.pk 2 1 0 120 48000 1 10
	pk full_m120.pk 2 1 0 120 8000 2 5
	rnd 1 3000 2 48000
	rnd 2 3000 1 48000
	rnd 3 3000 2 16000
	rnd 4 3000 1 8000
	rnd 5 3000 2 24000
} >"$O"

oracle_out $TD/encf_golden.txt
{
	echo "# Generated by tools/oracle/celt/gen.sh (encf.c): n synthetic"
	echo "# encode+decode cases of the shared band/energy/allocation/PVQ code per seed."
	for s in 1 2 3 4 5 6 7 8; do
		echo "encf seed=$s n=500 $("$W/encf" $s 500)"
	done
} >"$O"

# Hybrid replay logs: mono 16 kHz and stereo 48 kHz for every vector,
# plus stereo 24 and 8 kHz and mono 48 kHz for vectors 05, 06, 10, 12.
H=$W/hyblogs
rm -rf "$H"
mkdir -p "$H"
for v in 01 02 03 04 05 06 07 08 09 10 11 12; do
	cfgs="16000:1 48000:2"
	case $v in 05 | 06 | 10 | 12) cfgs="$cfgs 24000:2 48000:1 8000:2" ;; esac
	for c in $cfgs; do
		"$W/hyb" "$V/testvector$v.bit" "${c%:*}" "${c#*:}" "$H/v${v}_${c%:*}_${c#*:}.log" >/dev/null
	done
done
for c in 16000_1 48000_2; do
	oracle_out $TD/hybrid_v12_$c.log.gz
	gzip -9 -n -c "$H/v12_$c.log" >"$O"
done

# Encoder.
oracle_out $TD/enc_pcm.raw.gz
ex() { dd if="$V/testvector$1.dec" bs=19200 skip="$2" count="$3" status=none; }
{ ex 01 20 6; ex 11 50 6; ex 02 30 4; ex 05 60 4; ex 10 30 4; } >"$W/pcm.raw"
gzip -9 -n -c "$W/pcm.raw" >"$O"

python3 -I "$HERE/gen_cases.py" >"$W/cases.txt"
oracle_out $TD/enc_golden.txt
{
	echo "# Generated by tools/oracle/celt/gen.sh (encdrv.c, core cases of gen_cases.py)."
	"$W/encdrv" "$W/cases.txt" "$W/pcm.raw"
} >"$O"

oracle_out $TD/enc_vectors_golden.txt
{
	echo "# Generated by tools/oracle/celt/gen.sh (encdrv.c on the decoded vectors); needs OPUS_TESTVECTORS."
	for v in 01 02 03 04 05 06 07 08 09 10 11 12; do
		fr=$(($(stat -c %s "$V/testvector$v.dec") / 4))
		n() { echo $((fr / (120 << $1))); }
		cat >"$W/vc.txt" <<EOC
v${v}a vec=$v ch=2 lm=3 n=$(n 3) br=96000 vbr=1 cvbr=0 cx=10
v${v}b vec=$v ch=1 lm=2 n=$(n 2) br=32000 vbr=1 cvbr=1 cx=10 ana=1 seed=$v
v${v}c vec=$v ch=2 lm=1 n=$(n 1) br=64000 vbr=0 cx=7
v${v}d vec=$v ch=2 lm=3 n=$(n 3) start=17 end=21 ext=2 br=24000 vbr=1 cx=10 seed=$v
v${v}e vec=$v ch=1 lm=0 n=$(n 0) nb=40 cx=3
v${v}f vec=$v ch=2 lm=3 n=$(n 3) rnd=1 lmvar=1 seed=1$v br=48000 vbr=1 cx=9
EOC
		"$W/encdrv" "$W/vc.txt" "$V/testvector$v.dec"
	done
} >"$O"

echo "full hybrid replay logs: CELT_HYBRID_LOGS=$H"
oracle_finish
